export HAZARD_ML_MASTER_MAX_TRAIN_ROWS="${HAZARD_ML_MASTER_MAX_TRAIN_ROWS:-800000}"
export HAZARD_ML_MASTER_MAX_TEST_ROWS="${HAZARD_ML_MASTER_MAX_TEST_ROWS:-200000}"
export HAZARD_ML_SKIP_MASTER_FEATURE_REENGINEERING="${HAZARD_ML_SKIP_MASTER_FEATURE_REENGINEERING:-1}"

export RADIUS_LIST="${RADIUS_LIST:-40 60 75 100}"
export FORCE_RERUN="${FORCE_RERUN:-0}"
export FEATURE_RADIUS_FOLLOWS_TARGET="${FEATURE_RADIUS_FOLLOWS_TARGET:-1}"

cd "${SCRIPT_DIR}"

echo "[$(date -u +%Y-%m-%dT%H:%M:%SZ)] Starting separate v33 Day-2 radius workflow"
