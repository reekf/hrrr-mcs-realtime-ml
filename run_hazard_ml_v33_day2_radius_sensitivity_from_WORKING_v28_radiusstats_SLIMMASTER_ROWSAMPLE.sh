export NUMEXPR_NUM_THREADS="${NUMEXPR_NUM_THREADS:-1}"
export HAZARD_ML_RAY_USE_GPUS="${HAZARD_ML_RAY_USE_GPUS:-0}"
if [[ "${HAZARD_ML_RAY_USE_GPUS}" != "1" ]]; then
  export CUDA_VISIBLE_DEVICES=""
  export NVIDIA_VISIBLE_DEVICES=""
