#!/usr/bin/env bash
set -euo pipefail

# Separate Day-2 R40/R60/R75/R100 XGBoost training workflow.
# Event case V -> RAP V-1 09Z f03..f51 -> target V 12Z to V+1 12Z.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GENERATOR="make_run_hazard_ml_v33_day2_radius_sensitivity_from_WORKING_v28_radiusstats_SLIMMASTER_ROWSAMPLE.py"
