echo "RAP offsets: 0 6 12 18 24 30 36 42 48 (files f03..f51)"
echo "Target: MRMS >= FFG from case V 12Z through V+1 12Z"
echo "Project directory: ${PROJECT_DIR}"
echo "RADIUS_LIST=${RADIUS_LIST}"
echo "Resume from cached daily chunks=${HAZARD_ML_DAY2_RESUME_CACHED_CHUNKS}"
