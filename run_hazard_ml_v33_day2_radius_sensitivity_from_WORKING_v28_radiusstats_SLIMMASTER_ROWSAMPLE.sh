if [[ -n "${HAZARD_ML_PROJECT_DIR:-}" ]]; then
  PROJECT_DIR="${HAZARD_ML_PROJECT_DIR}"
elif [[ -d "${REMOTE_PROJECT_DIR}" ]]; then
  PROJECT_DIR="${REMOTE_PROJECT_DIR}"
elif [[ -d "${LOCAL_PROJECT_DIR}" ]]; then
  PROJECT_DIR="${LOCAL_PROJECT_DIR}"
else
  PROJECT_DIR="${REMOTE_PROJECT_DIR}"
fi
LOG_DIR="${PROJECT_DIR}/training_logs"
mkdir -p "${LOG_DIR}"

export HAZARD_ML_SCRIPT_DIR="${SCRIPT_DIR}"
export HAZARD_ML_PROJECT_DIR="${PROJECT_DIR}"
export HAZARD_ML_BASE_V28_RADIUSSTATS_SCRIPT="${HAZARD_ML_BASE_V28_RADIUSSTATS_SCRIPT:-${SCRIPT_DIR}/hazard_ml_training_v28_r100km_singletarget_radiusstats_regression_MEMSAFE_V3.py}"
export HAZARD_ML_V33_DAY2_GENERATED_SCRIPT_DIR="${HAZARD_ML_V33_DAY2_GENERATED_SCRIPT_DIR:-${SCRIPT_DIR}/generated_v33_day2_radius_sensitivity_slimmaster_rowsample}"

export OMP_NUM_THREADS="${OMP_NUM_THREADS:-1}"
