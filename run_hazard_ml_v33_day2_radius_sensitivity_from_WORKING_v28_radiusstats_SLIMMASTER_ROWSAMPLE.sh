export HAZARD_ML_FORCE_FRESH_RUN="${HAZARD_ML_FORCE_FRESH_RUN:-0}"
export HAZARD_ML_FORCE_RETRAIN_MODEL="${HAZARD_ML_FORCE_RETRAIN_MODEL:-1}"
export HAZARD_ML_DAY2_RESUME_CACHED_CHUNKS="${HAZARD_ML_DAY2_RESUME_CACHED_CHUNKS:-1}"
export HAZARD_ML_USE_RAY_FOR_DATA_EXTRACTION="${HAZARD_ML_USE_RAY_FOR_DATA_EXTRACTION:-0}"
export HAZARD_ML_RAY_MAX_IN_FLIGHT="${HAZARD_ML_RAY_MAX_IN_FLIGHT:-2}"
export HAZARD_ML_LOCAL_MODEL_N_JOBS="${HAZARD_ML_LOCAL_MODEL_N_JOBS:-1}"
export HAZARD_ML_LOCAL_OPTUNA_XGB_TRIALS="${HAZARD_ML_LOCAL_OPTUNA_XGB_TRIALS:-30}"
export HAZARD_ML_LOCAL_TUNE_MAX_TRAIN_ROWS_PER_FOLD="${HAZARD_ML_LOCAL_TUNE_MAX_TRAIN_ROWS_PER_FOLD:-300000}"
export HAZARD_ML_LOCAL_TUNE_MAX_VAL_ROWS_PER_FOLD="${HAZARD_ML_LOCAL_TUNE_MAX_VAL_ROWS_PER_FOLD:-100000}"

export HAZARD_ML_MASTER_COMBINE_BATCH_SIZE="${HAZARD_ML_MASTER_COMBINE_BATCH_SIZE:-2}"
export HAZARD_ML_MASTER_COMBINE_SLIM_WRITE="${HAZARD_ML_MASTER_COMBINE_SLIM_WRITE:-1}"
export HAZARD_ML_MASTER_SLIM_READ="${HAZARD_ML_MASTER_SLIM_READ:-1}"
